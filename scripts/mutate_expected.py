"""Known-bad variants of the agent0-derived expectations (development time only, issue #87).

For every translated request in fixtures/expected/<key>/expected.yaml, write variants that are wrong on
purpose, so each verifier's catch rate can be measured:

  agg_swap        structural  first aggregation avg<->sum, max<->min
  drop_by_label   structural  first `by (...)` loses its first label (the clause goes if it was the only one)
  rate_on_gauge   structural  otel_metric_type="sum" -> "gauge" on a selector inside rate()/irate()/increase()
  add_scale       structural  first PromQL wrapped as `100 * (<q>)` (only if 100 is not in the Datadog source)
  range_change    structural  first [$__rate_interval] -> [5m]
  sibling_metric  semantic    first metric with a catalog sibling of the same type and monotonicity under
                              the same prefix (up to the last dot) -> that sibling (next name in sorted
                              order, wrapping), in every PromQL string of the request
  outcome_flip    semantic    the translation becomes {outcome: blocked, errors: [MISSING_METRIC_MAPPING]}

Structural variants are detectable from the expectation and the source alone (scripts/lint_expected.py
should block or nit them); semantic ones need knowledge of what the metrics mean. Deterministic: no
randomness, same output every run. Every mutated PromQL string still parses.

Usage: uv run scripts/mutate_expected.py <service>/<dashboard_id> [...] | --all
Writes fixtures/oracle/verify/mutations/<key>.yaml: a list of
  {id: "<source_path>#<mutation>", source_path, mutation, structural, expected}
"""

from __future__ import annotations

import argparse
import copy
import re
from collections.abc import Callable
from pathlib import Path
from typing import Any

import yaml

import build_expected as be
import lint_expected as le
import verify_common as vc

STRUCTURAL = {
    "agg_swap": True,
    "drop_by_label": True,
    "rate_on_gauge": True,
    "add_scale": True,
    "range_change": True,
    "sibling_metric": False,
    "outcome_flip": False,
}
SWAP = {"avg": "sum", "sum": "avg", "max": "min", "min": "max"}
AGG_OP = re.compile(r"\b(avg|sum|max|min)(?=\s*(?:(?:by|without)\s*\([^)]*\)\s*)?\()")
BY_CLAUSE = re.compile(r"\bby\s*\(([^)]*)\)\s*")
RATE_SUM = re.compile(r'\b(?:rate|irate|increase)\(\s*\{[^{}]*?(otel_metric_type="sum")')
NAME = re.compile(r'otel_metric_name="([^"]+)"')

HEADER = """\
# GENERATED by scripts/mutate_expected.py. Known-bad variants of expected.yaml, never test input.
# Each verifier's verdicts on them go to <key>.<verifier>.yaml next to this file (catch rate).
"""

Mutator = Callable[[list[str], dict[str, Any]], "list[str] | None"]


def agg_swap(promql: list[str], request: dict[str, Any]) -> list[str] | None:
    for i, q in enumerate(promql):
        m = AGG_OP.search(le.mask_strings(q))
        if m:
            return [*promql[:i], q[: m.start()] + SWAP[m.group(1)] + q[m.end() :], *promql[i + 1 :]]
    return None


def drop_by_label(promql: list[str], request: dict[str, Any]) -> list[str] | None:
    for i, q in enumerate(promql):
        m = BY_CLAUSE.search(le.mask_strings(q))
        if not m:
            continue
        labels = [x.strip() for x in m.group(1).split(",") if x.strip()]
        if not labels:
            continue
        clause = f"by ({', '.join(labels[1:])}) " if len(labels) > 1 else ""
        return [*promql[:i], q[: m.start()] + clause + q[m.end() :], *promql[i + 1 :]]
    return None


def rate_on_gauge(promql: list[str], request: dict[str, Any]) -> list[str] | None:
    for i, q in enumerate(promql):
        masked = le.mask_strings(q)
        for m in RATE_SUM.finditer(q):
            # skip matches whose function name or label name sits inside a quoted string
            if masked[m.start()] != q[m.start()] or masked[m.start(1)] != q[m.start(1)]:
                continue
            return [*promql[:i], q[: m.start(1)] + 'otel_metric_type="gauge"' + q[m.end(1) :], *promql[i + 1 :]]
    return None


def add_scale(promql: list[str], request: dict[str, Any]) -> list[str] | None:
    if not promql or le.has_number(le.dd_numbers(request), 100.0):
        return None
    return [f"100 * ({promql[0]})", *promql[1:]]


def range_change(promql: list[str], request: dict[str, Any]) -> list[str] | None:
    for i, q in enumerate(promql):
        changed = le.replace_outside_strings(q, le.RATE_INTERVAL, "[5m]", count=1)
        if changed != q:
            return [*promql[:i], changed, *promql[i + 1 :]]
    return None


def sibling(name: str) -> str | None:
    """The next catalog metric after `name` (sorted, wrapping) with the same parent, type and
    monotonicity, so that only the meaning changes, not anything a structural check could see."""
    catalog = be.otel_catalog()
    if name not in catalog or "." not in name:
        return None
    parent, kind = name.rsplit(".", 1)[0], (catalog[name]["type"], catalog[name]["monotonic"])
    group = sorted(
        n for n in catalog if "." in n and n.rsplit(".", 1)[0] == parent and (catalog[n]["type"], catalog[n]["monotonic"]) == kind
    )
    if len(group) < 2:
        return None
    return group[(group.index(name) + 1) % len(group)]


def sibling_metric(promql: list[str], request: dict[str, Any]) -> list[str] | None:
    names = [n for q in promql for n in NAME.findall(q)]
    for name in dict.fromkeys(names):
        other = sibling(name)
        if other:
            return [q.replace(f'otel_metric_name="{name}"', f'otel_metric_name="{other}"') for q in promql]
    return None


PROMQL_MUTATORS: dict[str, Mutator] = {
    "agg_swap": agg_swap,
    "drop_by_label": drop_by_label,
    "rate_on_gauge": rate_on_gauge,
    "add_scale": add_scale,
    "range_change": range_change,
    "sibling_metric": sibling_metric,
}


def mutate_entry(request: dict[str, Any], expected: dict[str, Any]) -> list[dict[str, Any]]:
    """[{mutation, structural, expected}] for one translated request ([] if not translated)."""
    if expected.get("outcome") != "translated":
        return []
    promql = list(expected.get("promql") or [])
    out = []
    for kind, fn in PROMQL_MUTATORS.items():
        mutated = fn(promql, request)
        if mutated is None or mutated == promql:
            continue
        if any(le.parse_promql(q)[0] is None for q in mutated):
            raise ValueError(f"{kind} produced unparsable PromQL: {mutated}")
        exp = copy.deepcopy(expected)
        exp["promql"] = mutated
        out.append({"mutation": kind, "structural": STRUCTURAL[kind], "expected": exp})
    out.append(
        {
            "mutation": "outcome_flip",
            "structural": STRUCTURAL["outcome_flip"],
            "expected": {"outcome": "blocked", "errors": ["MISSING_METRIC_MAPPING"]},
        }
    )
    return out


def mutations_for(key: str) -> list[dict[str, Any]]:
    """Every variant of the dashboard, in case request order then mutation order."""
    requests = vc.case_requests(vc.load_case(key))
    out = []
    for entry in vc.load_expected(key)["requests"]:
        sp = entry["source_path"]
        for m in mutate_entry(requests[sp], entry["expected"]):
            out.append({"id": f"{sp}#{m['mutation']}", "source_path": sp, **m})
    return out


def write(key: str) -> tuple[Path, list[dict[str, Any]]]:
    out = vc.MUTATIONS_DIR / f"{key}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    items = mutations_for(key)
    out.write_text(HEADER + yaml.safe_dump(items, sort_keys=False, allow_unicode=True, width=1000))
    return out, items


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("keys", nargs="*", metavar="SVC/ID")
    parser.add_argument("--all", action="store_true", help="every dashboard in fixtures/oracle/dashboards.json")
    args = parser.parse_args(argv)
    keys = vc.all_keys() if args.all else args.keys
    if not keys:
        parser.error("give SVC/ID keys or --all")
    for key in keys:
        path, items = write(key)
        kinds = {k: sum(i["mutation"] == k for i in items) for k in STRUCTURAL}
        print(f"{le.display(path)}: {len(items)} variants ({', '.join(f'{k} {n}' for k, n in kinds.items() if n)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
